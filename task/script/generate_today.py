#!/usr/bin/env python3
"""
generate_today.py

Usage:
    python generate_today.py [--date YYYY-MM-DD] [--base-dir BASE_DIR]

Purpose:
    - Scan all .md task files under the task/by-task directory (with YAML front matter)
    - Parse YAML header fields: id, title, status, due, priority, category, etc.
    - Find:
        * Tasks due today with status != done
        * Tasks overdue with status != done
    - Generate a Markdown summary file so an LLM can read it and summarize for the user.

Recommended integration (for LLM / agent callers):
    When the user sends the message "today":
      1. An external tool / plugin calls this script.
      2. It reads the Markdown summary file generated by this script.
      3. The LLM uses that content to summarize and propose an action plan.
"""

import argparse
import datetime as _dt
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Dict, Any, Tuple

import sys

try:
    import yaml  # type: ignore
except Exception:
    # Allow a friendly error if PyYAML is not installed.
    yaml = None  # type: ignore


BASE_RELATIVE_TASK_DIR = Path("work-with-claude") / "task" / "by-task"
DEFAULT_OUTPUT_FILE = Path("work-with-claude") / "task" / "today.md"


@dataclass
class Task:
    id: str
    title: str
    status: str
    due: Optional[_dt.date]
    priority: Optional[str]
    category: Optional[str]
    path: Path
    raw_yaml: Dict[str, Any]

    @property
    def is_done(self) -> bool:
        return self.status.lower() == "done"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Scan task/by-task YAML tasks and generate a view for today / overdue tasks."
    )
    parser.add_argument(
        "--date",
        type=str,
        default=None,
        help="Specify the logical 'today' date (YYYY-MM-DD). Defaults to the current system date.",
    )
    # 默认的 base-dir 设为仓库根目录（即包含 task/ 的目录）
    # 当前脚本位于 task/script/generate_today.py
    # parents[0] = .../task/script
    # parents[1] = .../task
    # parents[2] = .../<repo-root>
    parser.add_argument(
        "--base-dir",
        type=str,
        default=str(Path(__file__).resolve().parents[2]),
        help=(
            "Base directory that contains the `task/` folder. "
            "Defaults to the repository root (two levels above this script)."
        ),
    )
    parser.add_argument(
        "--output",
        type=str,
        default=None,
        help="Output Markdown summary file path. "
        "Defaults to work-with-claude/task/today.md.",
    )
    return parser.parse_args()


def parse_date(value: Any) -> Optional[_dt.date]:
    if value is None:
        return None
    if isinstance(value, _dt.date):
        return value
    if isinstance(value, str):
        value = value.strip()
        if not value:
            return None
        try:
            return _dt.datetime.strptime(value, "%Y-%m-%d").date()
        except ValueError:
            return None
    return None


def extract_front_matter(text: str) -> Tuple[Optional[str], Optional[str]]:
    """
    Extract YAML front matter (the section wrapped with ---) from a Markdown string.

    Returns (yaml_text, rest_text).
    """
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None, text

    yaml_lines: List[str] = []
    end_index = None

    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            end_index = i
            break
        yaml_lines.append(lines[i])

    if end_index is None:
        # No closing --- found; treat as no front matter.
        return None, text

    yaml_text = "\n".join(yaml_lines)
    rest_text = "\n".join(lines[end_index + 1 :])
    return yaml_text, rest_text


def load_tasks(task_dir: Path) -> List[Task]:
    if yaml is None:
        print("Error: PyYAML is not installed. Please run `pip install pyyaml` first.", file=sys.stderr)
        sys.exit(1)

    tasks: List[Task] = []
    if not task_dir.exists():
        print(f"Warning: task directory does not exist: {task_dir}", file=sys.stderr)
        return tasks

    for path in sorted(task_dir.glob("*.md")):
        try:
            text = path.read_text(encoding="utf-8")
        except Exception as e:
            print(f"Skipping unreadable file {path}: {e}", file=sys.stderr)
            continue

        yaml_text, _ = extract_front_matter(text)
        if not yaml_text:
            print(f"Skipping file without YAML front matter: {path}", file=sys.stderr)
            continue

        try:
            data = yaml.safe_load(yaml_text) or {}
        except Exception as e:
            print(f"Failed to parse YAML in {path}: {e}", file=sys.stderr)
            continue

        tid = str(data.get("id", "")).strip()
        title = str(data.get("title", "")).strip()
        status = str(data.get("status", "todo")).strip()
        due = parse_date(data.get("due"))
        priority = data.get("priority")
        category = data.get("category")

        if not tid or not title:
            print(f"Skipping task file missing id/title: {path}", file=sys.stderr)
            continue

        tasks.append(
            Task(
                id=tid,
                title=title,
                status=status,
                due=due,
                priority=str(priority) if priority is not None else None,
                category=str(category) if category is not None else None,
                path=path,
                raw_yaml=data,
            )
        )

    return tasks


def classify_tasks(
    tasks: List[Task], today: _dt.date
) -> Tuple[List[Task], List[Task], List[Task], List[Task]]:
    today_tasks: List[Task] = []
    overdue_tasks: List[Task] = []
    upcoming_soon: List[Task] = []
    upcoming_week: List[Task] = []

    for t in tasks:
        if t.is_done or t.due is None:
            continue

        if t.due == today:
            today_tasks.append(t)
        elif t.due < today:
            overdue_tasks.append(t)
        else:
            # Future tasks
            delta = (t.due - today).days
            # 1) High-priority tasks within the next 3 days
            if delta <= 3 and (t.priority or "").lower() in {"high", "urgent"}:
                upcoming_soon.append(t)
            # 2) All tasks within the next 7 days (excluding today, which is handled above)
            if 1 <= delta <= 7:
                upcoming_week.append(t)

    # 按 due 日期和优先级排序
    def sort_key(t: Task):
        prio_rank = {"urgent": 0, "high": 1, "medium": 2, "low": 3}
        pr = prio_rank.get((t.priority or "").lower(), 4)
        return (t.due or today, pr, t.id)

    today_tasks.sort(key=sort_key)
    overdue_tasks.sort(key=sort_key)
    upcoming_soon.sort(key=sort_key)
    upcoming_week.sort(key=sort_key)

    return today_tasks, overdue_tasks, upcoming_soon, upcoming_week


def format_task_line(t: Task) -> str:
    due_str = t.due.isoformat() if t.due else "N/A"
    prio = t.priority or "-"
    rel_path = t.path.name
    # today.md 位于 task/ 下，任务文件位于 task/by-task/ 下，因此使用相对路径 by-task/<filename>
    link_target = f"by-task/{rel_path}"
    # 使用 Markdown 任务清单语法 + 可点击的任务链接（只展示 due 和 priority，去掉 category / file 等细节）
    return (
        f"- [ ] [**{t.id}** · {t.title}]({link_target})  "
        f"_(due: {due_str}, priority: {prio})_"
    )


def generate_markdown(
    today: _dt.date,
    today_tasks: List[Task],
    overdue_tasks: List[Task],
    upcoming_soon: List[Task],
    upcoming_week: List[Task],
) -> str:
    lines: List[str] = []
    lines.append(f"# Tasks for {today.isoformat()}")
    lines.append("")
    lines.append("> This file is auto-generated by `script/generate_today.py` "
                 "for an LLM / agent to read and summarize for the user.")
    lines.append("")

    # Tasks due today
    lines.append("## Due today (not done)")
    lines.append("")
    if today_tasks:
        for t in today_tasks:
            lines.append(format_task_line(t))
    else:
        lines.append("- No unfinished tasks due today.")
    lines.append("")

    # Overdue tasks
    lines.append("## Overdue (not done)")
    lines.append("")
    if overdue_tasks:
        for t in overdue_tasks:
            lines.append(format_task_line(t))
    else:
        lines.append("- No unfinished overdue tasks.")
    lines.append("")

    # High-priority tasks due soon
    lines.append("## High-priority tasks due within the next 3 days")
    lines.append("")
    if upcoming_soon:
        for t in upcoming_soon:
            lines.append(format_task_line(t))
    else:
        lines.append("- No high-priority tasks due within the next 3 days.")
    lines.append("")

    # All tasks due within the next 7 days
    lines.append("## Tasks due within the next 7 days")
    lines.append("")
    if upcoming_week:
        for t in upcoming_week:
            lines.append(format_task_line(t))
    else:
        lines.append("- No tasks due within the next 7 days.")
    lines.append("")

    return "\n".join(lines)


def main() -> None:
    args = parse_args()

    if args.date:
        try:
            today = _dt.datetime.strptime(args.date, "%Y-%m-%d").date()
        except ValueError:
            print(f"Invalid date format: {args.date}. Please use YYYY-MM-DD.", file=sys.stderr)
            sys.exit(1)
    else:
        today = _dt.date.today()

    base_dir = Path(args.base_dir).expanduser().resolve()
    task_dir = base_dir / "task" / "by-task"

    output_path = (
        Path(args.output).expanduser().resolve()
        if args.output
        else (base_dir / "task" / "today.md")
    )

    tasks = load_tasks(task_dir)
    today_tasks, overdue_tasks, upcoming_soon, upcoming_week = classify_tasks(tasks, today)
    md = generate_markdown(today, today_tasks, overdue_tasks, upcoming_soon, upcoming_week)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(md, encoding="utf-8")

    # 同时在 stdout 也打印一份，方便直接在终端看
    print(md)


if __name__ == "__main__":
    main()


